/**
 * Лёгкий «стеммер» для временного поиска средствами PostgreSQL: отрезает типичные окончания
 * украинских (и русских) слов, чтобы «склади» находило «складів», «складах», «склад».
 * Это не морфологический анализ — только для запроса (ищем подстроку-основу через LIKE).
 */
const ENDINGS = [
  // прикметники, дієприкметники
  'ими', 'ому', 'ого', 'ій', 'их', 'им', 'ою', 'ої', 'ий', 'ая', 'ее', 'ые', 'ым',
  // іменники: множина й відмінки
  'ією', 'ії', 'ія', 'ію', 'ами', 'ями', 'ах', 'ях', 'ів', 'їв', 'ям', 'ам', 'ом', 'ем', 'єм', 'ою', 'ею', 'ей', 'ой',
  // дієслова
  'ться', 'ється', 'ити', 'ати', 'ють', 'ують', 'ує', 'ить', 'ять',
  // однобуквені
  'а', 'я', 'и', 'і', 'ї', 'у', 'ю', 'е', 'є', 'о', 'ь', 'й',
].sort((a, b) => b.length - a.length)

export function stemWord(word: string): string {
  const w = word.toLowerCase()
  if (w.length < 5 || !/^[\p{Script=Cyrillic}ʼ'’-]+$/u.test(w)) return w
  for (const e of ENDINGS) {
    // Основа не короче 4 букв — иначе слишком много лишнего
    if (w.endsWith(e) && w.length - e.length >= 4) return w.slice(0, -e.length)
  }
  return w
}
